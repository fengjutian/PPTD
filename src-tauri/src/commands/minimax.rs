use serde::{Deserialize, Serialize};

#[derive(Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct GenerateRequest {
    topic: String,
    slide_count: u8,
}

#[derive(Serialize)]
struct ChatRequest {
    model: String,
    messages: Vec<Message>,
    temperature: f32,
}

#[derive(Serialize)]
struct Message {
    role: &'static str,
    content: String,
}

#[derive(Deserialize)]
struct ChatResponse {
    choices: Vec<Choice>,
}

#[derive(Deserialize)]
struct Choice {
    message: ResponseMessage,
}

#[derive(Deserialize)]
struct ResponseMessage {
    content: String,
}

#[tauri::command]
pub async fn generate_presentation(request: GenerateRequest) -> Result<serde_json::Value, String> {
    if request.topic.trim().is_empty()
        || request.topic.chars().count() > 4_000
        || !(1..=20).contains(&request.slide_count)
    {
        return Err("AI_REQUEST_INVALID".into());
    }
    let api_key = std::env::var("MINIMAX_API_KEY").map_err(|_| "MINIMAX_API_KEY_MISSING")?;
    let model = std::env::var("MINIMAX_MODEL").unwrap_or_else(|_| "MiniMax-M3".into());
    let prompt = format!(
        "为以下主题生成 {} 页中文演示文稿。仅返回严格 JSON，不要 Markdown：{{\"title\":\"文稿标题\",\"slides\":[{{\"title\":\"页面标题\",\"body\":\"3-5条简洁要点\",\"speakerNotes\":\"演讲备注\"}}]}}。slides 必须恰好 {} 项。主题：{}",
        request.slide_count, request.slide_count, request.topic.trim()
    );
    let body = ChatRequest {
        model,
        messages: vec![Message {
            role: "user",
            content: prompt,
        }],
        temperature: 0.4,
    };
    let response = reqwest::Client::new()
        .post("https://api.minimax.io/v1/text/chatcompletion_v2")
        .bearer_auth(api_key)
        .json(&body)
        .send()
        .await
        .map_err(|error| format!("MINIMAX_REQUEST_FAILED: {error}"))?;
    if !response.status().is_success() {
        return Err(format!("MINIMAX_HTTP_ERROR: {}", response.status()));
    }
    let payload: ChatResponse = response
        .json()
        .await
        .map_err(|error| format!("MINIMAX_RESPONSE_INVALID: {error}"))?;
    let content = payload
        .choices
        .first()
        .ok_or("MINIMAX_EMPTY_RESPONSE")?
        .message
        .content
        .trim();
    let content = content
        .strip_prefix("```json")
        .or_else(|| content.strip_prefix("```"))
        .unwrap_or(content)
        .strip_suffix("```")
        .unwrap_or(content)
        .trim();
    serde_json::from_str(content).map_err(|error| format!("MINIMAX_JSON_INVALID: {error}"))
}
